  function schedule(root) {
    pending.add(root || document);
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(() => {
      scheduled = false;
      const items = Array.from(pending);
      pending.clear();
      for (const item of items) translateNode(item);
    });
  }

  async function loadCards() {
    try {
      const response = await fetch(CARD_API, { credentials: 'include', cache: 'no-store' });
      if (!response.ok) return;
      const payload = await response.json();
      const cards = Array.isArray(payload) ? payload : (Array.isArray(payload && payload.data) ? payload.data : []);
      for (const card of cards) {
        const cnName = typeof card.name_cn === 'string' ? card.name_cn.trim() : '';
        const jpName = typeof card.name_jp === 'string' ? card.name_jp.trim() : '';
        const cnText = typeof card.card_text_cn === 'string' ? card.card_text_cn.trim() : '';
        const jpText = typeof card.card_text_jp === 'string' ? card.card_text_jp.trim() : '';
        if (cnName && jpName && cnName !== jpName) cardNames.set(cnName, jpName);
        if (cnText && jpText && cnText !== jpText) cardTexts.set(cnText, jpText);
      }
      const names = Array.from(cardNames.keys()).sort((a, b) => b.length - a.length);
      const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      cardNameRegex = names.length
        ? new RegExp(names.map(escapeRegExp).join('|'), 'gu')
        : null;
      schedule(document);
    } catch (error) {
      console.warn('[Loveca 日本語化] カードAPIの取得に失敗しました。UI翻訳のみ継続します。', error);
    }
  }


  function installCardApiJapanesePreference() {
    try {
      const pageWindow = typeof unsafeWindow !== 'undefined' ? unsafeWindow : window;
      if (!pageWindow || pageWindow.__lovecaJaFetchPatched || typeof pageWindow.fetch !== 'function') return;
      const originalFetch = pageWindow.fetch.bind(pageWindow);
      const transform = (value) => {
        if (Array.isArray(value)) return value.map(transform);
        if (!value || typeof value !== 'object') return value;
        const out = { ...value };
        const jpName = typeof out.name_jp === 'string' && out.name_jp.trim() ? out.name_jp : null;
        const jpText = typeof out.card_text_jp === 'string' && out.card_text_jp.trim() ? out.card_text_jp : null;
        const jpNameCamel = typeof out.nameJp === 'string' && out.nameJp.trim() ? out.nameJp : null;
        const jpTextCamel = typeof out.cardTextJp === 'string' && out.cardTextJp.trim() ? out.cardTextJp : null;
        if (jpName) out.name_cn = jpName;
        if (jpText) out.card_text_cn = jpText;
        if (jpNameCamel) out.nameCn = jpNameCamel;
        if (jpTextCamel) out.cardTextCn = jpTextCamel;
        for (const [key, child] of Object.entries(out)) {
          if (child && typeof child === 'object') out[key] = transform(child);
        }
        return out;
      };
      pageWindow.fetch = async function lovecaJaFetch(input, init) {
        const response = await originalFetch(input, init);
        try {
          const method = String((init && init.method) || (input && input.method) || 'GET').toUpperCase();
          const rawUrl = typeof input === 'string' ? input : input && input.url;
          if (method !== 'GET' || !rawUrl) return response;
          const url = new URL(rawUrl, pageWindow.location.href);
          if (url.origin !== pageWindow.location.origin || !url.pathname.startsWith('/api/cards')) return response;
          const type = response.headers.get('content-type') || '';
          if (!type.includes('application/json')) return response;
          const data = await response.clone().json();
          const headers = new Headers(response.headers);
          headers.delete('content-length');
          headers.delete('content-encoding');
          return new Response(JSON.stringify(transform(data)), {
            status: response.status,
            statusText: response.statusText,
            headers
          });
        } catch {
          return response;
        }
      };
      pageWindow.__lovecaJaFetchPatched = true;
    } catch (error) {
      console.warn('[Loveca 日本語化] カードAPI日本語優先化を適用できませんでした。DOM翻訳を継続します。', error);
    }
  }

