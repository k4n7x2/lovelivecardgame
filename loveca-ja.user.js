  function translateCore(text) {
    if (cardNames.has(text)) return cardNames.get(text);
    if (cardTexts.has(text)) return cardTexts.get(text);
    if (exact.has(text)) return exact.get(text);
    if (uiExact.has(text)) return uiExact.get(text);
    if (tutorialDetailExact.has(text)) return tutorialDetailExact.get(text);
    let out = text;
    if (cardNames.has(out)) out = cardNames.get(out);
    else if (cardTexts.has(out)) out = cardTexts.get(out);
    else if (exact.has(out)) out = exact.get(out);
    else if (uiExact.has(out)) out = uiExact.get(out);
    else if (tutorialDetailExact.has(out)) out = tutorialDetailExact.get(out);
    else if (siteExact.has(out)) out = siteExact.get(out);
    else if (siteExact2.has(out)) out = siteExact2.get(out);
    else {
      for (const rule of regex) {
        if (rule[0].test(out)) {
          out = out.replace(rule[0], rule[1]);
          break;
        }
      }
      if (out === text) {
        for (const rule of siteRegex2) {
          if (rule[0].test(out)) {
            out = out.replace(rule[0], rule[1]);
            break;
          }
        }
      }
      if (out === text) {
        for (const rule of siteRegex) {
          if (rule[0].test(out)) {
            out = out.replace(rule[0], rule[1]);
            break;
          }
        }
      }
    }
    if (cardNameRegex) out = out.replace(cardNameRegex, (name) => cardNames.get(name) || name);
    return out;
  }

  function translateString(value) {
    if (!value || typeof value !== 'string') return value;
    const core = value.trim();
    if (!core) return value;
    let translated = translateCore(core);
    const slashParts = translated.split(/\s+\/\s+/u);
    if (slashParts.length === 2 && slashParts[0] === slashParts[1]) translated = slashParts[0];
    if (translated === core) return value;
    const lead = value.match(/^\s*/u)[0];
    const tail = value.match(/\s*$/u)[0];
    return lead + translated + tail;
  }

  function editable(el) {
    return el instanceof Element && el.matches('input, textarea, [contenteditable=""], [contenteditable="true"]');
  }

  function translateElement(el) {
    if (!(el instanceof Element)) return;
    for (const attr of attrs) {
      if (!el.hasAttribute(attr)) continue;
      const before = el.getAttribute(attr) || '';
      const after = translateString(before);
      if (before !== after) el.setAttribute(attr, after);
    }
  }

  function translateNode(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      const parent = root.parentElement;
      if (!parent || skipTags.has(parent.tagName) || editable(parent)) return;
      const after = translateString(root.nodeValue || '');
      if (after !== root.nodeValue) root.nodeValue = after;
      return;
    }
    if (!(root instanceof Element) && !(root instanceof Document) && !(root instanceof DocumentFragment)) return;
    if (root instanceof Element) translateElement(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
      acceptNode(node) {
        if (node.nodeType === Node.ELEMENT_NODE) {
          if (skipTags.has(node.tagName)) return NodeFilter.FILTER_REJECT;
          if (editable(node)) {
            translateElement(node);
            return NodeFilter.FILTER_REJECT;
          }
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    let node;
    while ((node = walker.nextNode())) {
      if (node.nodeType === Node.TEXT_NODE) translateNode(node);
      else translateElement(node);
    }
    normalizeCardRows(root instanceof DocumentFragment ? document : root);
  }

  function normalizeCardRows(root) {
    if (!root.querySelectorAll) return;
    for (const label of root.querySelectorAll('span')) {
      const text = (label.textContent || '').trim();
      if (text === '中文' || text === '中国語') {
        const row = label.parentElement;
        if (row && !row.dataset.lovecaJaHiddenCn) {
          row.dataset.lovecaJaHiddenCn = '1';
          row.style.display = 'none';
        }
      } else if (text === '日文') {
        label.textContent = '日本語';
      }
    }
  }

  let scheduled = false;
